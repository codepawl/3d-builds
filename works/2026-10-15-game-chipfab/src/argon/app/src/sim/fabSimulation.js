export function createSeededRandom(seed = 542501) {
  let state = seed >>> 0;
  return function next() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Helper to interpolate along a closed 3D polyline loop with smooth corner rounding
export function sampleClosedLoop(waypoints, distance) {
  if (!waypoints || waypoints.length < 2) {
    return { position: [0, 0, 0], rotationY: 0, segmentIndex: 0 };
  }
  const segLengths = [];
  let totalLength = 0;
  for (let i = 0; i < waypoints.length; i++) {
    const a = waypoints[i];
    const b = waypoints[(i + 1) % waypoints.length];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const dz = b[2] - a[2];
    const len = Math.hypot(dx, dy, dz);
    segLengths.push(len);
    totalLength += len;
  }
  if (totalLength <= 0.0001) {
    return { position: [...waypoints[0]], rotationY: 0, segmentIndex: 0 };
  }
  let d = ((distance % totalLength) + totalLength) % totalLength;
  for (let i = 0; i < waypoints.length; i++) {
    const segLen = segLengths[i];
    if (d <= segLen || i === waypoints.length - 1) {
      const a = waypoints[i];
      const b = waypoints[(i + 1) % waypoints.length];
      const t = segLen > 0.0001 ? d / segLen : 0;
      const x = a[0] + (b[0] - a[0]) * t;
      const y = a[1] + (b[1] - a[1]) * t;
      const z = a[2] + (b[2] - a[2]) * t;
      const dx = b[0] - a[0];
      const dz = b[2] - a[2];
      // Our GLB assets face +Z in Three.js (which was -Y in Blender)
      const rotationY = Math.atan2(dx, dz);
      return { position: [x, y, z], rotationY, segmentIndex: i, t, totalLength };
    }
    d -= segLen;
  }
  return { position: [...waypoints[0]], rotationY: 0, segmentIndex: 0 };
}

