// Advance simulation state deterministically for any given simTime (in seconds)
export function updateSimulationAtTime(state, simTime) {
  state.simTime = simTime;

  for (let i = 0; i < state.units.length; i++) {
    const u = state.units[i];

    // 1. Update OHT Vehicles along ceiling monorail loops + hoist drop cycle
    if (u.category === 'oht' && u.loopKey) {
      const loop = OHT_LOOPS[u.loopKey] || OHT_LOOPS.fab1;
      // Smooth travel with periodic brief pause at dropStopDist to lower hoist
      const rawDist = u.loopOffset + simTime * u.speedMps;
      const sample = sampleClosedLoop(loop, rawDist);
      u.position[0] = sample.position[0];
      u.position[1] = sample.position[1];
      u.position[2] = sample.position[2];
      u.rotationY = sample.rotationY;

      // Hoist cycles smoothly when near a tool load port
      const hoistWave = Math.max(0, Math.sin(simTime * 1.35 + i * 1.9));
      u.hoistDropMeters = hoistWave > 0.72 ? ((hoistWave - 0.72) / 0.28) * 1.45 : 0;
      u.stepProgress = Math.round(((rawDist % 40) / 40) * 100);
    }

    // 2. Update Campus Road Trucks / Tankers & Cleanroom PGV Carts
    if (u.category === 'vehicle') {
      const loop = u.loopKey === 'pgv' ? PGV_SPINE_LOOP : CAMPUS_ROAD_LOOP;
      const rawDist = (u.loopOffset || 0) + simTime * (u.speedMps || 2.5);
      const sample = sampleClosedLoop(loop, rawDist);
      u.position[0] = sample.position[0];
      u.position[1] = sample.position[1];
      u.position[2] = sample.position[2];
      u.rotationY = sample.rotationY;
      u.stepProgress = Math.round(((rawDist % 60) / 60) * 100);
    }

    // 3. Update Rigged Cleanroom Engineers along bay patrol paths
    if (u.category === 'engineer' && u.patrolPoints && u.patrolPoints.length >= 2) {
      // Alternate between walking between consoles and pausing to inspect/repair
      const cycle = (simTime + (u.patrolOffset || 0)) % 14.0;
      if (cycle < 10.2) {
        const walkDist = ((simTime + (u.patrolOffset || 0)) * (u.patrolSpeed || 0.9));
        const sample = sampleClosedLoop(u.patrolPoints, walkDist);
        u.position[0] = sample.position[0];
        u.position[1] = sample.position[1];
        u.position[2] = sample.position[2];
        u.rotationY = sample.rotationY;
        u.clipState = u.state === 'maintenance' ? 'Repair_Tool' : 'Walk';
      } else {
        // Face nearest tool row (North -Z or South +Z) and inspect console
        u.rotationY = u.position[2] < 0 ? Math.PI : 0;
        u.clipState = u.state === 'maintenance' ? 'Repair_Tool' : 'Inspect_Console';
      }
      u.stepProgress = Math.round(((simTime * 6 + i * 17) % 100));
    }

    // 4. Update Process Tool live progress & micro-telemetry
    if (u.category === 'tool' || u.category === 'stocker') {
      const baseProg = (u.stepProgress || 50);
      u.liveProgress = Math.min(99, Math.max(8, Math.round((baseProg + simTime * 2.4 + i * 11) % 100)));
      const utilWave = Math.sin(simTime * 0.4 + i * 0.8) * 0.6;
      u.liveUtilization = Number(Math.min(99.8, Math.max(60.0, u.utilization + utilWave)).toFixed(1));
      u.liveWph = Math.round(u.wafersPerHour + Math.sin(simTime * 0.5 + i) * 3);
    }
  }

  // Update Wafer Lots progress & active Hot Lot stage index (cycles smoothly so timeline is alive)
  for (let j = 0; j < state.tasks.length; j++) {
    const lot = state.tasks[j];
    lot.liveProgress = Math.min(99, Math.max(12, Math.round((lot.progress + simTime * 2.1 + j * 13) % 100)));
  }

  return state;
}

// Compute live KPIs for the currently selected site
export function getSiteLiveKpis(state, siteId) {
  const site = state.sites.find((s) => s.id === siteId) || state.sites[0];
  const t = state.simTime || 0;
  const wspdDelta = Math.round(Math.sin(t * 0.35) * 18 + Math.cos(t * 0.19) * 9);
  const yieldDelta = Math.sin(t * 0.27) * 0.12;
  const cycleDelta = Math.cos(t * 0.22) * 0.15;
  const availDelta = Math.sin(t * 0.31 + 1.2) * 0.2;

  // Determine active stage in the 7-stage Hot Lot route (advances smoothly over time or when user clicks a stage)
  const route = state.hotLotRoutes[siteId] || state.hotLotRoutes.fab1;
  const activeStageIndex = Math.floor((t / 9.0) % route.stages.length);

  return {
    wspd: site.baseKpis.wspd + wspdDelta,
    lineYield: (site.baseKpis.lineYield + yieldDelta).toFixed(1),
    cycleTimeDays: (site.baseKpis.cycleTimeDays + cycleDelta).toFixed(1),
    toolAvailability: (site.baseKpis.toolAvailability + availDelta).toFixed(1),
    activeLots: site.baseKpis.activeLots,
    ohtUtilization: (site.baseKpis.ohtUtilization + availDelta).toFixed(1),
    activeStageIndex,
    stageProgress: Math.round(((t % 9.0) / 9.0) * 100),
  };
}
