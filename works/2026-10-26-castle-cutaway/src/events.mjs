import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, mkdirSync } from 'node:fs';
import { chromium } from '../../demo-harness/node_modules/playwright/index.mjs';
import { serveFolder } from '../pokemon-duel/serve.mjs';
const here = dirname(fileURLToPath(import.meta.url));
const server = await serveFolder(here);
const browser = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
await page.goto(`${server.origin}/index.html?t=0`, { waitUntil: 'load' });
await page.waitForFunction(() => window.sceneReady === true, null, { timeout: 90000 });
const data = await page.evaluate(() => window.getEvents());
mkdirSync(join(here, 'sound'), { recursive: true });
data.camera = await page.evaluate(() => Array.from({ length: 201 }, (_, i) => ({ t: i / 10, ...window.cameraAt(i / 10) })));
writeFileSync(join(here, 'sound', 'events.json'), JSON.stringify(data, null, 1));
const counts = {};
for (const event of data.events) counts[event.kind] = (counts[event.kind] ?? 0) + 1;
console.log(JSON.stringify(counts));
await browser.close();
server.close();
